void generate_patterns(const int K, const int N, int *dataset) {
    for(int y=0; y<K; y++)
        for(int x=0; x<K; x++)
            dataset[y*K+x] = (x+y) % N;

    for(int i=0; i<K*K/40; i++) {
        int p = rand() % (K*K);
        dataset[p] = rand() % N;
    }

}

Mode_t get_mode(char *mode) {
    if (strcmp(mode, "random") == 0) {
        return RANDOM_NOISE;
    }
    if (strcmp(mode, "sparse-seed") == 0) {
        return SPARSE_SEED;
    }
    if (strcmp(mode, "random-noise-shaped") == 0) {
        return RANDOM_NOISE_SHAPE;
    }
    if (strcmp(mode, "random-pattern") == 0) {
        return RANDOM_PATTERN;
    }
    return 0; // this is not valid
}
