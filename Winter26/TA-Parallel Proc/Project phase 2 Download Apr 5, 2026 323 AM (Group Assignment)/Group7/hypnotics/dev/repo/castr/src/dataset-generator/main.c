#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

typedef enum {
    RANDOM_NOISE = 1,
    SPARSE_SEED = 2,
    RANDOM_NOISE_SHAPE = 3,
    RANDOM_PATTERN = 4
} Mode_t;

Mode_t get_mode(char *mode);

void generate_random_noise(const int K,const int N, int *dataset);
void generate_patterns(const int K, const int N, int *dataset);

int main(int argc, char **argv) {
    if (argc < 5) {
        fprintf(stderr, "Invalid input, input should be formatted dataset-generato <out> <mode> <K> <N>, where: out is the file where this will be written\nmode is a string that determines generation\n K is the width and height\n N is the max number for each points\n");
        exit(EXIT_FAILURE);
    }

    const int K = atoi(argv[3]);
    const int N = atoi(argv[4]);

    int *dataset = malloc(sizeof(int)*K*K);
    if (dataset == NULL) {
        fprintf(stderr, "Failed to allocate memory for dataset\n");
        exit(EXIT_FAILURE);
    }

    switch (get_mode(argv[2])) {
    case RANDOM_NOISE:
        generate_random_noise(K, N, dataset);
        break;
    case SPARSE_SEED:
        break;
    case RANDOM_NOISE_SHAPE:
        generate_random_noise(K, N, dataset);
        break;
    case RANDOM_PATTERN:
        generate_patterns(K,N,dataset);
      break;
    default:
        fprintf(stderr, "Input %s is not a valid mode\n", argv[2]);
        free(dataset);
        exit(EXIT_FAILURE);
    }

    FILE *fp = fopen(argv[1], "wb");
    if (fp == NULL) {
        fprintf(stderr, "Something went wrong opening this file\n");
        free(dataset);
        exit(EXIT_FAILURE);
    }
    fwrite(&N, sizeof(int), 1, fp);
    fwrite(&K, sizeof(int), 1, fp);
    fwrite(dataset, sizeof(int), K*K, fp);

    fclose(fp);
    free(dataset);
    return 0;
}
void generate_random_noise(const int K, const int N, int *dataset) {
    srand(time(NULL));
    for(int i=0; i<K*K; i++){
        dataset[i] = rand() % N;
    }

}

